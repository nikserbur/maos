/**
 * Единица изделия словами (владелец: «компл» в таблицах — нечитаемо): сокращения справочника раскрываются
 * с согласованием по числу — «12 комплектов», «3 упаковки»; стандартные обозначения (шт, кг, т, м, л)
 * остаются как есть. Число форматирует вызывающий (src/explain/format.ts).
 */
import { plural, type PluralForms } from '../../explain/format'

const WORDS: Readonly<Record<string, PluralForms>> = {
  'компл': ['комплект', 'комплекта', 'комплектов'],
  'компл.': ['комплект', 'комплекта', 'комплектов'],
  'кмпл': ['комплект', 'комплекта', 'комплектов'],
  'уп': ['упаковка', 'упаковки', 'упаковок'],
  'уп.': ['упаковка', 'упаковки', 'упаковок'],
  'пар': ['пара', 'пары', 'пар'],
  'пог. м': ['погонный метр', 'погонных метра', 'погонных метров'],
  'пог.м': ['погонный метр', 'погонных метра', 'погонных метров'],
}

/** Единица после числа `value`: сокращение — словом в нужной форме, стандартная — как есть. */
export function unitWord(unit: string, value: number): string {
  const forms = WORDS[unit.trim().toLowerCase()]
  return forms ? plural(Math.abs(value), forms) : unit
}
