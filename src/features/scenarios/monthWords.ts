/**
 * Месяцы полностью в готовом тексте таблиц (владелец: «сокращения у слов в таблицах»): «ЦБ РФ, сент. 2026» →
 * «ЦБ РФ, сентябрь 2026», «февр.–авг. 2022» → «февраль–август 2022». Для ячеек сравнения сценариев,
 * где подписи приходят из общих словарей с короткими месяцами.
 */
const FULL: ReadonlyArray<readonly [RegExp, string]> = [
  [/янв\./g, 'январь'], [/февр\./g, 'февраль'], [/апр\./g, 'апрель'], [/авг\./g, 'август'],
  [/сент\./g, 'сентябрь'], [/окт\./g, 'октябрь'], [/нояб\./g, 'ноябрь'], [/дек\./g, 'декабрь'],
]

/** Сокращённые названия месяцев в тексте → полные; прочий текст не меняется. */
export function fullMonths(text: string): string {
  return FULL.reduce((t, [re, word]) => t.replace(re, word), text)
}
