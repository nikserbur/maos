export function AgentLayersSection() {
  return (
    <Section
      id="agent-layers"
      stages={[['w3', 'L0 + L2 сразу, L1 позже'], ['done', 'методология согласована']]}
      lead={<>Идея «агенты обучаются внутри заданной системы уравнений и балансов, а над ними обучается регулятор»
        переносится на один завод: агенты — диспетчеры станков, регулятор — планировщик завода.</>}
    >
      <Figure id="agent-layers" caption={<>Планировщик L2 задаёт внутренние цены машино-часа и бонусы заказам;
        диспетчеры L0 (одна политика на тип рабочего центра) выбирают операцию, когда станок освобождается;
        среда — дискретно-событийный симулятор MAOS, где материальный баланс соблюдается по построению.</>} />
      <p>
        <b>L0 — диспетчер станка.</b> Решает в момент освобождения станка, какую операцию из очереди взять
        (или выждать). Все станки одного типа используют общую политику и видят усреднённое состояние «соседей»
        (приближение среднего поля при K ≈ 1–10 станков на тип). <b>L2 — планировщик завода.</b> Раз в период
        назначает цены машино-часа по типам РЦ и бонусы заказам; его цель — CVaR прибыли завода по сценариям.
        <b> L1 — начальник цеха</b> (веса правил, лимит задела) вводится позже.
      </p>
      <Formula note="жёсткие ограничения — маски действий, мягкие — PID-лагранжиан">
        r<sub>L0</sub> = −Δ(нижняя оценка Cmax) − c<sub>T</sub>·Δ(просрочка) − c<sub>S</sub>·переналадки;
        J<sub>L2</sub> = CVaR<sub>α</sub>(прибыль завода)
      </Formula>
      <Callout tone="note" title="Почему не PINN-штрафы">
        Материальный баланс, предшествование и мощности соблюдаются самим симулятором и маскированием недопустимых
        действий — это точнее штрафа в функции потерь. Физически-информированные слои (проекция KKT) применяются
        только в обучаемом суррогате для ускорения планировщика L2.
      </Callout>
    </Section>
  )
}

